"use client";

import React, { useMemo, useState } from "react";
import {
  ColumnDef,
  flexRender,
  getCoreRowModel,
  getFilteredRowModel,
  getPaginationRowModel,
  useReactTable,
} from "@tanstack/react-table";
import { cn } from "@/lib/utils";
import { Checkbox } from "@/components/ui/checkbox";
import { Avatar, AvatarFallback, AvatarImage } from "@/components/ui/avatar";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";
import { Copy, ExternalLink, Trash2, Maximize2 } from "lucide-react";
import { SortFromTopToBottom } from "@solar-icons/react";
import { toast } from "sonner";
import Link from "next/link";
import { useDeleteReferral, useReferrals } from "@/hooks/useReferrals";
import type { ReferralEntityType } from "@/lib/api/referralApi";

interface ReferrerData {
  id: string;
  name: string;
  email: string;
  avatarUrl: string;
  referralLink: string;
  clicks: number;
  clicksRecent: number;
  registrations: number;
  registrationsRecent: number;
}

interface ReferralsTableProps {
  baseUrl: string;
  entityType: ReferralEntityType;
  entityId: string;
}
export const ReferralsTable: React.FC<ReferralsTableProps> = ({
  baseUrl,
  entityType,
  entityId,
}) => {
  const [rowSelection, setRowSelection] = useState({});
  const { data } = useReferrals(entityType, entityId);
  const deleteMutation = useDeleteReferral(entityType, entityId);
  const rows: ReferrerData[] = (data?.data ?? []).map((row) => ({
    id: row.id,
    name:
      [row.referrer.firstName, row.referrer.lastName].filter(Boolean).join(" ") ||
      "Referrer",
    email: row.referrer.email,
    avatarUrl: row.referrer.imageUrl ?? "",
    referralLink: `${
      typeof window !== "undefined" ? window.location.origin : "https://www.oppskills.com"
    }/r/${row.code}`,
    clicks: row.clicksCount,
    clicksRecent: row.clicksRecent ?? 0,
    registrations: row.registrationsCount,
    registrationsRecent: row.registrationsRecent ?? 0,
  }));

  const columns = useMemo<ColumnDef<ReferrerData>[]>(
    () => [
      {
        id: "select",
        header: ({ table }) => (
          <div className="flex justify-center w-full">
            <Checkbox
              checked={table.getIsAllPageRowsSelected()}
              onCheckedChange={(value) => table.toggleAllPageRowsSelected(!!value)}
              className="border-white! data-[state=checked]:bg-white! data-[state=checked]:text-primary-800!"
            />
          </div>
        ),
        cell: ({ row }) => (
          <div className="flex justify-center w-full">
            <Checkbox
              checked={row.getIsSelected()}
              onCheckedChange={(value) => row.toggleSelected(!!value)}
              className="border-neutral-300 data-[state=checked]:bg-primary-800 data-[state=checked]:text-white"
            />
          </div>
        ),
      },
      {
        id: "sno",
        header: "S. No.",
        cell: (info) => <span className="text-neutral-600 font-medium px-2">{info.row.index + 1}</span>,
      },
      {
        accessorKey: "name",
        header: () => (
          <div className="flex items-center gap-2">
            Generated by/ Link <SortFromTopToBottom size={18} className="ml-1 opacity-60" />
          </div>
        ),
        cell: (info) => {
          const row = info.row.original;
          return (
            <Link href={`${baseUrl}/${row.id}`} className="flex items-center gap-4 py-2 group/name cursor-pointer">
              <Avatar className="w-12 h-12 rounded-full border border-neutral-100 group-hover/name:border-primary-200 transition-colors">
                <AvatarImage src={row.avatarUrl} className="object-cover" />
                <AvatarFallback>{row.name.charAt(0)}</AvatarFallback>
              </Avatar>
              <div className="flex flex-col gap-0.5">
                <span className="font-bold text-neutral-900 text-base group-hover/name:text-primary-800 transition-colors">{row.name}</span>
                <span className="text-xs text-neutral-500 font-medium">{row.email}</span>
                <div className="flex items-center gap-2 mt-1" onClick={(e) => e.stopPropagation()}>
                  <span className="text-xs text-blue-600 font-medium">{row.referralLink}</span>
                  <button
                    onClick={() => {
                      navigator.clipboard.writeText(row.referralLink);
                      toast.success("Link copied!");
                    }}
                    className="text-neutral-400 hover:text-neutral-600"
                  >
                    <Copy size={14} />
                  </button>
                  <button className="text-neutral-400 hover:text-neutral-600">
                    <ExternalLink size={14} />
                  </button>
                </div>
              </div>
            </Link>
          );
        },
      },
      {
        accessorKey: "clicks",
        header: () => (
          <div className="flex items-center gap-2 justify-center">
            Link Clicks <SortFromTopToBottom size={18} className="ml-1 opacity-60" />
          </div>
        ),
        cell: (info) => {
          const row = info.row.original;
          return (
            <div className="flex flex-col items-center gap-1">
              <Badge className="bg-accent-yellow-100 text-accent-yellow-500 hover:bg-accent-yellow-100 border-none font-bold px-3 py-1 rounded-sm text-sm">
                {row.clicks} Clicks
              </Badge>
              <span className="text-[11px] text-neutral-400 font-medium">
                {row.clicksRecent} in last 24 hrs
              </span>
            </div>
          );
        },
      },
      {
        accessorKey: "registrations",
        header: () => (
          <div className="flex items-center gap-2 justify-center">
            Registrations <SortFromTopToBottom size={18} className="ml-1 opacity-60" />
          </div>
        ),
        cell: (info) => {
          const row = info.row.original;
          return (
            <div className="flex flex-col items-center gap-1">
              <Badge className="bg-accent-pink-100 text-accent-pink-500 hover:bg-accent-pink-100 border-none font-bold px-3 py-1 rounded-sm text-sm">
                {row.registrations} Registrations
              </Badge>
              <span className="text-[11px] text-neutral-400 font-medium">
                {row.registrationsRecent.toString().padStart(2, "0")} in last 24 hrs
              </span>
            </div>
          );
        },
      },
      {
        id: "view",
        header: "View Referrals",
        cell: (info) => (
          <div className="flex justify-center">
            <Link href={`${baseUrl}/${info.row.original.id}`}>
              <Button
                variant="outline"
                className="rounded-xl h-10 px-4 flex items-center gap-2 bg-[#342636] hover:bg-[#271B40] text-white border-none shadow-sm transition-all active:scale-95"
              >
                <Maximize2 size={16} />
                <span className="text-xs font-semibold">View list</span>
              </Button>
            </Link>
          </div>
        ),
      },
      {
        id: "delete",
        header: "Delete",
        cell: (info) => (
          <div className="flex justify-center">
            <button
              className="text-red-500 hover:text-red-700 transition-colors p-2"
              onClick={() => deleteMutation.mutate(info.row.original.id)}
            >
              <Trash2 size={20} />
            </button>
          </div>
        ),
      },
    ],
    []
  );

  const table = useReactTable({
    data: rows,
    columns,
    state: {
      rowSelection,
    },
    onRowSelectionChange: setRowSelection,
    getCoreRowModel: getCoreRowModel(),
    getFilteredRowModel: getFilteredRowModel(),
    getPaginationRowModel: getPaginationRowModel(),
  });

  return (
    <div className="w-full rounded-2xl overflow-hidden border border-neutral-200 bg-white shadow-sm">
      <Table className="min-w-[1000px] border-collapse!">
        <TableHeader className="bg-primary-800 hover:bg-primary-800!">
          {table.getHeaderGroups().map((headerGroup) => (
            <TableRow key={headerGroup.id} className="hover:bg-transparent! border-b-primary-900 border-b!">
              {headerGroup.headers.map((header) => (
                <TableHead
                  key={header.id}
                  className={cn(
                    "text-white font-semibold py-5 px-6 whitespace-nowrap",
                    (header.id === "clicks" ||
                      header.id === "registrations" ||
                      header.id === "view" ||
                      header.id === "delete") &&
                    "text-center"
                  )}
                  style={{
                    width: header.id === "select" ? "60px" : header.id === "sno" ? "80px" : "auto",
                  }}
                >
                  {header.isPlaceholder
                    ? null
                    : flexRender(header.column.columnDef.header, header.getContext())}
                </TableHead>
              ))}
            </TableRow>
          ))}
        </TableHeader>
        <TableBody>
          {table.getRowModel().rows.length === 0 ? (
            <TableRow>
              <TableCell colSpan={columns.length} className="h-24 text-center text-neutral-500">
                No referrers found.
              </TableCell>
            </TableRow>
          ) : (
            table.getRowModel().rows.map((row) => (
              <TableRow
                key={row.id}
                className="hover:bg-neutral-50/50 border-neutral-100 group transition-colors"
              >
                {row.getVisibleCells().map((cell) => (
                  <TableCell
                    key={cell.id}
                    className={cn(
                      "py-3 px-6",
                      (cell.column.id === "clicks" ||
                        cell.column.id === "registrations" ||
                        cell.column.id === "view" ||
                        cell.column.id === "delete") &&
                      "text-center"
                    )}
                  >
                    {flexRender(cell.column.columnDef.cell, cell.getContext())}
                  </TableCell>
                ))}
              </TableRow>
            ))
          )}
        </TableBody>
      </Table>
    </div>
  );
};
