"use client";

import React, { memo, useCallback, useMemo, useState } from "react";
import {
  ColumnDef,
  flexRender,
  getCoreRowModel,
  getFilteredRowModel,
  getPaginationRowModel,
  useReactTable,
} from "@tanstack/react-table";
import { EmptyState } from "@/components/common/EmptyState";
import { cn } from "@/lib/utils";
import { Checkbox } from "@/components/ui/checkbox";
import { Avatar, AvatarFallback, AvatarImage } from "@/components/ui/avatar";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import {
  Table,
  TableBody,
  TableCell,
  TableHead,
  TableHeader,
  TableRow,
} from "@/components/ui/table";
import { Copy, ExternalLink, Trash2, Maximize2 } from "lucide-react";
import { SortFromTopToBottom } from "@solar-icons/react";
import { toast } from "sonner";
import Link from "next/link";
import { useDeleteReferral, useReferrals } from "@/hooks/referrals/useReferrals";
import type { ReferralEntityType } from "@/lib/api/referralApi";
import { ReferrerDetailsSheet } from "./ReferrerDetailsSheet";
import { BoneyardSkeleton } from "@/components/boneyard/boneyard-skeleton";
import { TableBlockFallback } from "@/components/boneyard/loading-fallbacks";

interface ReferrerData {
  id: string;
  name: string;
  email: string;
  avatarUrl: string;
  referralLink: string;
  clicks: number;
  clicksRecent: number;
  registrations: number;
  registrationsRecent: number;
  institution?: string;
  location?: string;
  profession?: string;
  registrationDate?: string;
}

interface ReferralsTableProps {
  baseUrl: string;
  entityType: ReferralEntityType;
  entityId: string;
  isReadOnly?: boolean;
}

export const ReferralsTable: React.FC<ReferralsTableProps> = memo(
  ({ baseUrl, entityType, entityId, isReadOnly = false }) => {
    const [rowSelection, setRowSelection] = useState({});
    const { data, isLoading } = useReferrals(entityType, entityId);
    const deleteMutation = useDeleteReferral(entityType, entityId);

    const handleDelete = useCallback(
      (id: string) => deleteMutation.mutate(id),
      [deleteMutation],
    );

    const appOrigin =
      typeof window !== "undefined"
        ? window.location.origin
        : "https://www.oppskills.com";

    const rows: ReferrerData[] = useMemo(
      () =>
        (data?.data ?? []).map((row) => ({
          id: row.id,
          name:
            `${row.referrer.firstName ?? ""} ${row.referrer.lastName ?? ""}`.trim() ||
            "User",
          email: row.referrer.email,
          avatarUrl: row.referrer.imageUrl || "",
          referralLink: `${appOrigin}/r/${row.code}`,
          clicks: row.clicksCount,
          clicksRecent: row.clicksRecent ?? 0,
          registrations: row.registrationsCount,
          registrationsRecent: row.registrationsRecent ?? 0,
          institution: row.referrer.institution,
          location: row.referrer.location,
          profession: row.referrer.profession,
          registrationDate: row.referrer.registrationDate,
        })),
      [appOrigin, data?.data],
    );

    const [selectedReferrerId, setSelectedReferrerId] = useState<string | null>(
      null,
    );

    const columns = useMemo<ColumnDef<ReferrerData>[]>(
      () => [
        {
          id: "select",
          header: ({ table }) => (
            <div className="flex justify-center w-full">
              <Checkbox
                checked={table.getIsAllPageRowsSelected()}
                onCheckedChange={(value) =>
                  table.toggleAllPageRowsSelected(!!value)
                }
                className="border-white! data-[state=checked]:bg-white! data-[state=checked]:text-primary-800!"
              />
            </div>
          ),
          cell: ({ row }) => (
            <div className="flex justify-center w-full">
              <Checkbox
                checked={row.getIsSelected()}
                onCheckedChange={(value) => row.toggleSelected(!!value)}
                className="border-neutral-300 data-[state=checked]:bg-primary-800 data-[state=checked]:text-white"
              />
            </div>
          ),
        },
        {
          id: "sno",
          header: "S. No.",
          cell: (info) => (
            <span className="text-neutral-600 font-medium px-2">
              {info.row.index + 1}
            </span>
          ),
        },
        {
          accessorKey: "name",
          header: () => (
            <div className="flex items-center gap-2">
              Generated by/ Link{" "}
              <SortFromTopToBottom size={18} className="ml-1 opacity-60" />
            </div>
          ),
          cell: (info) => {
            const row = info.row.original;
            return (
              <div className="flex items-center gap-4 py-2">
                <button
                  type="button"
                  onClick={() => setSelectedReferrerId(row.id)}
                  className="flex min-w-0 shrink-0 items-center gap-4 group/name cursor-pointer text-left focus:outline-none"
                >
                  <Avatar className="w-12 h-12 shrink-0 rounded-full border border-neutral-100 group-hover/name:border-primary-200 transition-colors">
                    <AvatarImage src={row.avatarUrl} className="object-cover" />
                    <AvatarFallback>{row.name.charAt(0)}</AvatarFallback>
                  </Avatar>
                  <div className="flex flex-col min-w-0">
                    <span className="font-bold text-neutral-900 group-hover/name:text-primary-800 transition-colors truncate">
                      {row.name}
                    </span>
                    <span className="text-xs text-neutral-500 font-medium truncate">
                      {row.email}
                    </span>
                    <div className="flex items-center gap-2 mt-1">
                      <span className="text-[10px] text-primary-600 underline truncate max-w-[120px]">
                        {row.referralLink}
                      </span>
                      <button
                        type="button"
                        onClick={(e) => {
                          e.stopPropagation();
                          void navigator.clipboard.writeText(row.referralLink);
                          toast.success("Link copied!");
                        }}
                        className="text-neutral-400 hover:text-primary-600 transition-colors cursor-pointer"
                      >
                        <Copy size={12} />
                      </button>
                      <Link
                        href={row.referralLink}
                        target="_blank"
                        prefetch={false}
                        onClick={(e) => e.stopPropagation()}
                        className="text-neutral-400 hover:text-primary-600 transition-colors"
                      >
                        <ExternalLink size={12} />
                      </Link>
                    </div>
                  </div>
                </button>
              </div>
            );
          },
        },
        {
          accessorKey: "clicks",
          header: () => (
            <div className="flex items-center gap-2 justify-center">
              Link Clicks{" "}
              <SortFromTopToBottom size={18} className="ml-1 opacity-60" />
            </div>
          ),
          cell: (info) => {
            const row = info.row.original;
            return (
              <div className="flex flex-col items-center gap-1">
                <Badge className="bg-yellow-100 text-yellow-700 px-3 py-1 rounded text-sm hover:bg-yellow-100">
                  {row.clicks.toString().padStart(2, "0")} Clicks
                </Badge>
                <span className="text-xs text-neutral-500">
                  {row.clicksRecent.toString().padStart(2, "0")} in last 24 hrs
                </span>
              </div>
            );
          },
        },
        {
          accessorKey: "registrations",
          header: () => (
            <div className="flex items-center gap-2 justify-center">
              Registrations{" "}
              <SortFromTopToBottom size={18} className="ml-1 opacity-60" />
            </div>
          ),
          cell: (info) => {
            const row = info.row.original;
            return (
              <div className="flex flex-col items-center gap-1">
                <Badge className="bg-pink-100 text-pink-600 px-3 py-1 rounded text-sm hover:bg-pink-100">
                  {row.registrations.toString().padStart(2, "0")} Registrations
                </Badge>
                <span className="text-xs text-neutral-500">
                  {row.registrationsRecent.toString().padStart(2, "0")} in last
                  24 hrs
                </span>
              </div>
            );
          },
        },
        {
          id: "view",
          header: "View",
          cell: (info) => (
            <div className="flex justify-center">
              <button
                type="button"
                className="text-primary-600 hover:text-primary-800 transition-colors p-2"
                onClick={() => setSelectedReferrerId(info.row.original.id)}
              >
                <Maximize2 size={20} />
              </button>
            </div>
          ),
        },
        ...(!isReadOnly
          ? [
              {
                id: "delete",
                header: "Delete",
                cell: (info: any) => (
                  <div className="flex justify-center">
                    <button
                      className="text-red-500 hover:text-red-700 transition-colors p-2"
                      onClick={() => handleDelete(info.row.original.id)}
                    >
                      <Trash2 size={20} />
                    </button>
                  </div>
                ),
              },
            ]
          : []),
      ],
      [handleDelete, appOrigin, isReadOnly],
    );

    const table = useReactTable({
      data: rows,
      columns,
      getCoreRowModel: getCoreRowModel(),
      getFilteredRowModel: getFilteredRowModel(),
      getPaginationRowModel: getPaginationRowModel(),
    });

    return (
      <div className="w-full rounded-2xl overflow-hidden border border-neutral-200 bg-white shadow-sm">
        <BoneyardSkeleton
          loading={isLoading || !data}
          name={`referrals-table-${entityId}`}
          fallback={<TableBlockFallback className="px-0 py-0" />}
          className="w-full"
        >
          {rows.length > 0 ? (
            <Table className="min-w-[1000px] border-collapse!">
              <TableHeader className="bg-primary-800 hover:bg-primary-800!">
                {table.getHeaderGroups().map((headerGroup) => (
                  <TableRow
                    key={headerGroup.id}
                    className="hover:bg-transparent! border-b-primary-900 border-b!"
                  >
                    {headerGroup.headers.map((header) => (
                      <TableHead
                        key={header.id}
                        className={cn(
                          "text-white font-semibold py-5 px-6 whitespace-nowrap",
                          (header.id === "clicks" ||
                            header.id === "registrations" ||
                            header.id === "view" ||
                            header.id === "delete") &&
                            "text-center",
                        )}
                        style={{
                          width:
                            header.id === "select"
                              ? "60px"
                              : header.id === "sno"
                                ? "80px"
                                : "auto",
                        }}
                      >
                        {header.isPlaceholder
                          ? null
                          : flexRender(
                              header.column.columnDef.header,
                              header.getContext(),
                            )}
                      </TableHead>
                    ))}
                  </TableRow>
                ))}
              </TableHeader>
              <TableBody>
                {table.getRowModel().rows.map((row) => (
                  <TableRow
                    key={row.id}
                    className="hover:bg-neutral-50/50 border-neutral-100 group transition-colors"
                  >
                    {row.getVisibleCells().map((cell) => (
                      <TableCell
                        key={cell.id}
                        className={cn(
                          "py-3 px-6",
                          (cell.column.id === "clicks" ||
                            cell.column.id === "registrations" ||
                            cell.column.id === "view" ||
                            cell.column.id === "delete") &&
                            "text-center",
                        )}
                      >
                        {flexRender(
                          cell.column.columnDef.cell,
                          cell.getContext(),
                        )}
                      </TableCell>
                    ))}
                  </TableRow>
                ))}
              </TableBody>
            </Table>
          ) : (
            <EmptyState
              title="No Referrals Found"
              description="No one has generated a referral link for this opportunity yet."
            />
          )}
        </BoneyardSkeleton>

        <ReferrerDetailsSheet
          referralId={selectedReferrerId}
          onClose={() => setSelectedReferrerId(null)}
        />
      </div>
    );
  },
);
